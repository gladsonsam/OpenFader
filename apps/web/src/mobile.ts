// ---- App-update notice (Tauri updater scaffold) ----

/** Payload of the backend's one-shot `openmix-updater` event (see
 * `src-tauri/src/lib.rs`): a newer signed release exists. The shell
 * never installs automatically — download/install UI is future work. */
export interface UpdaterNotice {
  version: string;
  current_version: string;
}

/**
 * Listen for the backend's update notice. No-op outside the Tauri
 * runtime (browser/PWA); resolves to an unsubscribe function. Never
 * throws: a missing event plugin just yields a dead subscription.
 */
export async function onUpdaterAvailable(cb: (n: UpdaterNotice) => void): Promise<() => void> {
  if (!isTauri()) return () => {};
  try {
    const { listen } = await import('@tauri-apps/api/event');
    return await listen<UpdaterNotice>('openmix-updater', (e) => {
      try {
        cb(e.payload);
      } catch {
        /* ignore */
      }
    });
  } catch {
    return () => {};
  }
}

// ---- Persistent store (Tauri) with localStorage fallback ----

export interface AppSettings {
  host?: string;
  [key: string]: unknown;
}

interface StoreLike {
  get<T>(key: string): Promise<T | null | undefined>;
  set(key: string, value: unknown): Promise<void>;
  save(): Promise<void>;
  clear(): Promise<void>;
}

/** Cached store handle: `load()` once, reuse across accesses (was one
 * `load('settings.json', …)` + `save()` per access). Reset on failure so
 * the next access retries instead of pinning a dead handle. */
let storePromise: Promise<StoreLike | null> | null = null;

async function getStore(): Promise<StoreLike | null> {
  if (!isTauri()) return null;
  if (!storePromise) {
    storePromise = import('@tauri-apps/plugin-store').then(
      async (m) => {
        try {
          return (await m.load('settings.json', { autoSave: false })) as StoreLike;
        } catch {
          return null;
        }
      },
      () => null,
    );
  }
  const store = await storePromise;
  if (!store) storePromise = null;
  return store;
}

export async function loadSettings(): Promise<AppSettings> {
  if (!isTauri()) {
    try {
      return JSON.parse(localStorage.getItem('openmix-settings') ?? '{}') as AppSettings;
    } catch {
      return {};
    }
  }
  try {
    const store = await getStore();
    if (!store) return {};
    return ((await store.get<AppSettings>('settings')) ?? {}) as AppSettings;
  } catch {
    return {};
  }
}

let settingsWrites: Promise<void> = Promise.resolve();
let settingsResetting = false;

/** All saves share a queue so reset cannot be followed by an older save. */
export function saveSettings(patch: AppSettings): Promise<void> {
  if (settingsResetting) return Promise.resolve();
  settingsWrites = settingsWrites.then(() => writeSettings(patch));
  return settingsWrites;
}

/** Clear the native store even when this session has not loaded it yet. */
export async function clearNativeSettings(): Promise<void> {
  settingsResetting = true;
  await settingsWrites;
  if (!isTauri()) return;
  const store = await getStore();
  if (!store) throw new Error('Could not open the native settings store. Retry clearing storage.');
  await store.clear();
  await store.save();
}

/** A failed reset leaves the page open for retry/cancel and normal use. */
export function resumeSettingsAfterFailedReset(): void {
  settingsResetting = false;
}

async function writeSettings(patch: AppSettings): Promise<void> {
  if (!isTauri()) {
    try {
      const cur = JSON.parse(localStorage.getItem('openmix-settings') ?? '{}') as AppSettings;
      localStorage.setItem('openmix-settings', JSON.stringify({ ...cur, ...patch }));
    } catch {
      /* ignore */
    }
    return;
  }
  try {
    const store = await getStore();
    if (!store) return;
    const cur = ((await store.get<AppSettings>('settings')) ?? {}) as AppSettings;
    await store.set('settings', { ...cur, ...patch });
    await store.save();
  } catch {
    /* ignore */
  }
}

// ---- App visibility (background battery + push gate) ----
//
// The engine push stream (Tauri Channel / `openmix-event` / poll fallback
// in `ui/world/transport.ts`) stays live in the background — an idle phone
// holds no JS timer in push mode and must not gain one here. Canvas
// painting pauses: meter loops check `isAppHidden()` and skip `draw()`
// while hidden.
//
// The backend is told too (mobile freeze fix): while the WebView is
// suspended it reads nothing, so Rust would keep queueing every meter /
// GR / tap frame into the WebView IPC queue (~1.7k messages/s) until
// resume chokes on the backlog. On hide we call `engine_set_active(false)`
// (Rust keeps draining the engine mailbox but drops the frames); on show
// `engine_set_active(true)` + `engine_resync`, which queues one fresh
// snapshot so desk changes made while hidden arrive in a single batch.
// Both calls are fire-and-forget and no-ops outside the Tauri runtime.
//
// Wiring: `initAppVisibility()` is called unconditionally from `main.ts`
// boot (works in browser/PWA too, not just the Tauri shell). Tauri window
// events (`onWindowEvent` focus/close) are deliberately not used: real
// mobile suspend is covered by Rust `WindowEvent::Suspended`/`Resumed`,
// and JS `visibilitychange` + `pagehide`/`pageshow` cover the WebView.

let visibilityInit = false;
let appHidden = typeof document !== 'undefined' ? document.hidden : false;
const foregroundCbs = new Set<() => void>();
const backgroundCbs = new Set<() => void>();

/** True while the app is backgrounded (hidden tab / suspended WebView). */
export function isAppHidden(): boolean {
  try {
    if (typeof document !== 'undefined' && document.hidden) return true;
  } catch {
    /* ignore */
  }
  return appHidden;
}

/** Run `cb` on every background → foreground transition. */
export function onAppForeground(cb: () => void): () => void {
  foregroundCbs.add(cb);
  return () => {
    foregroundCbs.delete(cb);
  };
}

/** Run `cb` on every foreground → background transition (WebView hide /
 * mobile suspend). */
export function onAppBackground(cb: () => void): () => void {
  backgroundCbs.add(cb);
  return () => {
    backgroundCbs.delete(cb);
  };
}

function fireForeground(): void {
  foregroundCbs.forEach((cb) => {
    try {
      cb();
    } catch {
      /* ignore */
    }
  });
}

function fireBackground(): void {
  backgroundCbs.forEach((cb) => {
    try {
      cb();
    } catch {
      /* ignore */
    }
  });
}

/** Pause the backend push stream (Tauri only, fire-and-forget). */
async function setEngineActive(active: boolean): Promise<void> {
  if (!isTauri()) return;
  try {
    const { invoke } = await import('@tauri-apps/api/core');
    await invoke('engine_set_active', { active });
  } catch {
    /* older shell without the command: fall back to the pre-fix behavior */
  }
}

/** Resume: re-enable push, then ask for one fresh snapshot (Tauri only). */
async function resumeEngine(): Promise<void> {
  if (!isTauri()) return;
  try {
    const { invoke } = await import('@tauri-apps/api/core');
    await invoke('engine_set_active', { active: true });
    await invoke('engine_resync');
    window.dispatchEvent(new Event('openmix-engine-resumed'));
  } catch {
    /* older shell without the commands */
  }
}

function handleHidden(): void {
  const was = appHidden;
  appHidden = true;
  if (!was) fireBackground();
  void setEngineActive(false);
}

function handleVisible(): void {
  const was = appHidden;
  appHidden = typeof document !== 'undefined' ? document.hidden : false;
  if (appHidden || !was) return;
  fireForeground();
  void resumeEngine();
}

/** Idempotent: track `visibilitychange` + `pagehide`/`pageshow`. No-op
 * without a DOM (node tests). Safe to call outside the Tauri runtime. */
export function initAppVisibility(): void {
  if (visibilityInit || typeof document === 'undefined') return;
  visibilityInit = true;
  appHidden = document.hidden;
  // A full-page storage reset/reload runs pagehide in the old document,
  // pausing native push. The new document starts visible, so it has no
  // hidden -> visible transition to resume that shared native gate.
  if (!appHidden) void resumeEngine();
  document.addEventListener('visibilitychange', () => {
    if (document.hidden) handleHidden();
    else handleVisible();
  });
  // `pagehide`/`pageshow` cover mobile WebView suspend where
  // `visibilitychange` can lag or never fire.
  try {
    window.addEventListener('pagehide', handleHidden);
    window.addEventListener('pageshow', () => {
      if (!document.hidden) handleVisible();
    });
  } catch {
    /* non-browser shell */
  }
}
